def event_for(d: str, declared: str) -> str:
    """The note says which sale it is; this only catches a date that contradicts it."""
    y, m, day = (int(x) for x in d.split("-"))
    in_bf = (m, day) >= (11, 10) and (m, day) <= (12, 2)
    in_bd = (m, day) >= (12, 24) or (m, day) <= (1, 15)
    if declared == "黑五季" and not in_bf:
        raise SystemExit(f"{d} 标成黑五季但不在 11-10..12-02 窗口内")
    if declared == "节礼日" and not in_bd:
        raise SystemExit(f"{d} 标成节礼日但不在 12-24..01-15 窗口内")
    return declared


def build_points() -> list[dict]:
    rows = []
    for i, (nk, key, item, model, cat, retailer, price, was, cond, ev, extra) in enumerate(
        POINTS, 1
    ):
        nid, tok, d, declared, nnote = NOTES[nk]
        note = nnote if not extra else f"{nnote}；{extra}"
        rows.append(
            {
                "id": f"xhs-{i:03d}",
                "key": key,
                "item": item,
                "model": model,
                "category": cat,
                "retailer": retailer,
                "date": d,
                "event": event_for(d, declared),
                "price": price,
                "was_price": was,
                "was_suspect": False,
                "conditions": cond,
                "votes": None,
                "history_low": False,
                "source": SOURCE.format(nid=nid, tok=tok),
                "evidence": ev[:200],
                "retrieved_at": RETRIEVED_AT,
                "note": note,
            }
        )
    return rows


def build_promos() -> list[dict]:
    rows = []
    for i, (nk, retailer, kind, value, start, end, scope, cond, ev) in enumerate(PROMOS, 1):
        nid, tok, d, _declared, nnote = NOTES[nk]
        rows.append(
            {
                "id": f"xhsp-{i:03d}",
                "year": int((start or end or d)[:4]),
                "retailer": retailer,
                "kind": kind,
                "value": value,
                "start": start,
                "end": end,
                "scope": scope,
                "conditions": cond,
                "votes": None,
                "source": SOURCE.format(nid=nid, tok=tok),
                "evidence": ev[:200],
                "retrieved_at": RETRIEVED_AT,
                "note": nnote,
            }
        )
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", default="data/bf2026", type=Path)
    args = ap.parse_args()

    points, promos = build_points(), build_promos()
    for sub, rows in (("points", points), ("promos", promos)):
        path = args.out_dir / sub / "xhs.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{path}: {len(rows)} 行")

    spans = sorted({r["date"] for r in points})
    print(f"日期跨度 {spans[0]} ~ {spans[-1]}；笔记 {len({r['source'] for r in points})} 篇")
    print(f"带原价的行 {sum(1 for r in points if r['was_price'])}/{len(points)}")
    assert date.fromisoformat(RETRIEVED_AT)
    return 0


